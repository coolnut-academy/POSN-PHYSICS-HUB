function startMockTest() {
    const topic = document.getElementById('mock-topic').value;
    const count = parseInt(document.getElementById('mock-count').value);
    
    let filtered = topic === 'all' ? questionBank : questionBank.filter(q => q.topic === topic);
    
    // Shuffle and slice
    filtered = filtered.sort(() => 0.5 - Math.random()).slice(0, count);
    
    if(filtered.length === 0) {
        alert('ไม่พบข้อสอบในหมวดหมู่นี้');
        return;
    }
    
    state.mockTest = {
        active: true,
        questions: filtered,
        currentIndex: 0,
        score: 0
    };
    
    document.getElementById('mock-setup').classList.add('hidden');
    document.getElementById('mock-summary').classList.add('hidden');
    document.getElementById('mock-active').classList.remove('hidden');
    
    renderMockQuestion();
}

function renderMockQuestion() {
    const q = state.mockTest.questions[state.mockTest.currentIndex];
    
    document.getElementById('mock-progress').innerText = `ข้อ ${state.mockTest.currentIndex + 1} / ${state.mockTest.questions.length}`;
    document.getElementById('mock-topic-badge').innerText = q.topic.toUpperCase();
    document.getElementById('mock-question-text').innerHTML = q.prompt;
    
    document.getElementById('mock-answer-input').value = '';
    document.getElementById('mock-answer-input').disabled = false;
    document.getElementById('mock-check-btn').classList.remove('hidden');
    document.getElementById('mock-feedback').classList.add('hidden');
    
    setTimeout(rerenderMath, 50);
}

function checkMockAnswer() {
    const q = state.mockTest.questions[state.mockTest.currentIndex];
    const userInput = document.getElementById('mock-answer-input').value.trim();
    
    if(userInput === '') return;
    
    document.getElementById('mock-answer-input').disabled = true;
    document.getElementById('mock-check-btn').classList.add('hidden');
    
    const feedbackStatus = document.getElementById('mock-feedback-status');
    const isCorrect = (userInput.toLowerCase() === q.correctAnswer.toLowerCase());
    
    if(isCorrect) {
        state.mockTest.score++;
        feedbackStatus.innerText = '✅ ถูกต้อง!';
        feedbackStatus.className = 'text-2xl font-bold mb-4 text-green-400';
    } else {
        feedbackStatus.innerText = '❌ ยังไม่ถูกต้อง';
        feedbackStatus.className = 'text-2xl font-bold mb-4 text-red-400';
    }
    
    document.getElementById('mock-feedback-correct').innerHTML = `\\( ${q.answerLatex} \\)`;
    document.getElementById('mock-feedback-solution').innerHTML = q.solution ? renderDetailedSolution(q.solution) : q.detailedSolution;
    const mistakeContainer = document.getElementById('mock-feedback-mistake-container');
    if (q.solution) {
        if(mistakeContainer) mistakeContainer.classList.add('hidden');
    } else {
        if(mistakeContainer) mistakeContainer.classList.remove('hidden');
        document.getElementById('mock-feedback-mistake').innerHTML = q.commonMistake;
    }
    
    document.getElementById('mock-feedback').classList.remove('hidden');
    setTimeout(rerenderMath, 50);
}

function nextMockQuestion() {
    state.mockTest.currentIndex++;
    if(state.mockTest.currentIndex < state.mockTest.questions.length) {
        renderMockQuestion();
    } else {
        finishMockTest();
    }
}


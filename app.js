// Setup MathJax reload helper
function rerenderMath() {
    if (window.MathJax) {
        // Clear previous typeset info to prevent memory leaks and speed up re-rendering
        MathJax.typesetClear();
        MathJax.typesetPromise().catch(err => console.error("MathJax error:", err));
    }
}

// Navigation router
function navigate(viewId) {
    document.querySelectorAll('.view-section').forEach(el => {
        el.classList.add('hidden');
        el.classList.remove('fade-in');
    });
    
    const target = document.getElementById('view-' + viewId);
    if(target) {
        target.classList.remove('hidden');
        target.classList.add('fade-in');
    }

    // Call specific renders
    if(viewId === 'home') renderHome();
    if(viewId === 'theory') renderTheoryList();
    if(viewId === 'formula') renderFormulaMap();
    if(viewId === 'progress') renderProgress();
    if(viewId === 'sim') loadSimulations();

    // Re-render math explicitly
    setTimeout(rerenderMath, 50);
}

